function wavesKeys(): KeySpec[] {
  const keys: KeySpec[] = [K0(0, IDLE)];
  const t0 = 0.12 - 0.0375;
  for (let j = 0; j <= 12; j++) {
    const high = j % 2 === 0;
    const step = Math.floor(j / 4);
    keys.push(
      K0(
        t0 + j * 0.075,
        {
          c: [40 + j * 0.8, high ? 35 : 37],
          yaw: high ? 15 : -15,
          lean: 3,
          rf: [44 + step * 5, 62],
          lf: [34 + step * 5 + (j % 4 >= 2 ? 3 : 0), 62],
          rh: high ? [50, 30] : [58, 45],
          az: 0,
          el: high ? 65 : -45,
        },
        j === 0 ? 'io' : 'lin',
        j > 0,
      ),
    );
  }
  keys.push(K0(1.0, { c: [50, 36], yaw: 0, lean: 3, rf: [54, 62], lf: [49, 62], rh: [56, 38], az: 0, el: 0 }, 'out'));
  keys.push(K0(1.15, IDLE, 'io'));
  return keys;
}
