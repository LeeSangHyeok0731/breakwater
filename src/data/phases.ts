import { MONSTERS, type MonsterKind } from './monsters';

export interface SpawnGroup {
  kind: MonsterKind;
  count: number;
  elite?: boolean;
}

/** 특별 스테이지 미션: 웨이브 대신 몬스터가 계속 몰려온다. */
export type Mission =
  | { kind: 'survive'; seconds: number }
  | { kind: 'kills'; target: number };

export type Theme = 'day' | 'dusk' | 'night' | 'lava' | 'church' | 'castle' | 'horror' | 'void' | 'nest' | 'boneyard' | 'storm' | 'hell' | 'throne';

export interface PhaseDef {
  id: string;
  name: string;
  type: 'normal' | 'special' | 'boss';
  /** 챕터 번호 (게시판에서 묶어 보여 준다) */
  chapter: number;
  desc: string;
  /** 이 페이즈를 열려면 먼저 클리어해야 하는 페이즈 */
  requires?: string;
  hpMul: number;
  /** 몬스터 공격력 배율 (없으면 1) */
  dmgMul?: number;
  /** 맵 가로 길이(px) */
  width: number;
  /** 발판 [왼쪽 x, 윗면 y, 너비] (px). 땅의 윗면은 y=312 */
  platforms: [number, number, number][];
  theme: Theme;
  /** 일반·보스 페이즈의 웨이브 */
  waves: SpawnGroup[][];
  /** 특별 스테이지 */
  mission?: Mission;
  /** 특별 스테이지에서 계속 나오는 몬스터 (가중치) */
  spawnPool?: { kind: MonsterKind; weight: number; elite?: boolean }[];
  clearReward: { gold: number; exp: number; materials: Record<string, number>; sweepTickets: number };
}

