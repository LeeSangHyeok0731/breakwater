/**
 * 군단장 초상화 (작전 지휘관 창의 선택 카드).
 * 전투에서 쓰는 리그 파츠는 머리가 11~15픽셀이라 얼굴을 보여 주기엔 작다.
 * 그래서 같은 색과 생김새로 40×40 흉상을 따로 그린다 (살짝 오른쪽을 본다).
 * 그림은 처음 쓸 때 한 번만 만들어 data URL로 둔다.
 */

const SIZE = 40;
const cache = new Map<LegionId, string>();

export function legionPortraitUrl(id: LegionId): string {
  let url = cache.get(id);
  if (!url) {
    const a = new PixelArt(SIZE, SIZE);
    PAINT[id](a);
    url = a.toCanvas().toDataURL();
    cache.set(id, url);
  }
  return url;
}

